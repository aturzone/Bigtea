#[cfg(test)]
mod tests {
    use super::*;

    fn vocab() -> Vec<Vec<u8>> {
        vec![
            b"y".to_vec(),
            b"es".to_vec(),
            b"no".to_vec(),
            b"maybe".to_vec(),
            Vec::new(),
        ]
    }

    #[test]
    fn the_mask_admits_a_continuation_and_refuses_the_rest() {
        let g = Grammar::parse(r#"root ::= "yes" | "no""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);

        let start = c.allowed(b"");
        assert!(start.is_allowed(0), "`y` starts yes");
        assert!(start.is_allowed(2), "`no` is a whole alternative");
        assert!(!start.is_allowed(3), "`maybe` is in neither");

        let after_y = c.allowed(b"y");
        assert!(after_y.is_allowed(1), "`es` completes yes");
        assert!(!after_y.is_allowed(2), "`no` cannot follow `y`");
        assert!(!after_y.is_allowed(0));
    }

    /// A grammar that accepts everything passes any test that only checks
    /// acceptance, so the refusal above is the half that carries the weight.
    /// This pins that the mask is not simply all-ones.
    #[test]
    fn a_constraint_actually_constrains() {
        let g = Grammar::parse(r#"root ::= "yes""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);
        let mask = c.allowed(b"");
        assert!(mask.allowed_count() < v.len(), "everything was allowed");
        assert_eq!(mask.allowed_count(), 1);
    }

    #[test]
    fn a_completed_grammar_admits_nothing_and_says_so() {
        let g = Grammar::parse(r#"root ::= "no""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);
        let mask = c.allowed(b"no");
        assert!(mask.is_empty(), "nothing may follow a completed grammar");
    }

    #[test]
    fn a_prefix_that_already_violates_the_grammar_gives_an_empty_mask() {
        let g = Grammar::parse(r#"root ::= "yes""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);
        assert!(c.allowed(b"zzz").is_empty());
    }

    /// A token that decodes to nothing can never advance the grammar, so
    /// allowing it lets the model emit control tokens forever while the
    /// constraint never progresses.
    #[test]
    fn tokens_that_decode_to_nothing_are_never_allowed() {
        let g = Grammar::parse(r#"root ::= "yes""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);
        assert!(!c.allowed(b"").is_allowed(4));
        assert_eq!(c.empty_tokens(), &[4]);
    }

    /// A token may end half way through a character. Rejecting that would mask
    /// every byte-fallback token and make non-ASCII output impossible.
    #[test]
    fn a_token_ending_mid_character_is_allowed_if_it_could_still_match() {
        let g = Grammar::parse("root ::= [\u{4e00}-\u{9fff}]+").expect("parses");
        // The three bytes of U+4E2D, split as two tokens.
        let v: Vec<Vec<u8>> = vec![vec![0xE4], vec![0xB8, 0xAD], b"z".to_vec()];
        let c = Constraint::new(g, &v);
        let start = c.allowed(b"");
        assert!(
            start.is_allowed(0),
            "a lead byte could still become a match"
        );
        assert!(!start.is_allowed(2), "an ASCII letter cannot");
    }

    #[test]
    fn apply_sets_disallowed_logits_to_negative_infinity() {
        let g = Grammar::parse(r#"root ::= "no""#).expect("parses");
        let v = vocab();
        let c = Constraint::new(g, &v);
        let mut logits = vec![1.0f32; v.len()];
        c.allowed(b"").apply(&mut logits);
        assert_eq!(logits[2], 1.0, "`no` stays");
        assert!(logits[3].is_infinite() && logits[3].is_sign_negative());
    }

    #[test]
    fn the_incremental_matcher_agrees_with_replaying_the_prefix() {
        let g = Grammar::parse(r#"root ::= "a" "b" "c""#).expect("parses");
        let v: Vec<Vec<u8>> = vec![b"a".to_vec(), b"b".to_vec(), b"c".to_vec()];
        let c = Constraint::new(g, &v);

        let mut m = c.grammar().matcher();
        assert!(m.accept_str("a"));
        let incremental = c.allowed_from(&m);
        let replayed = c.allowed(b"a");
        assert_eq!(incremental, replayed);
        assert!(incremental.is_allowed(1) && !incremental.is_allowed(0));
    }
}
